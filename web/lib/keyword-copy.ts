// 분야 슬러그로 떨어지는 경우를 위한 별칭. 이름에서 주제를 못 읽은 키워드가
// door-window-sash / wallpaper-flooring 분야로 오면 각각 문·도배 문구를 쓴다.
TABLE['door-window-sash'] = TABLE.door
TABLE['wallpaper-flooring'] = TABLE.wallpaper

const fill = (s: string, keywordName: string) => s.replaceAll('{k}', keywordName)

/**
 * 키워드 이름과 분야로 공종 문구를 고른다.
 * 이름에서 읽은 주제 → 분야 슬러그 → general 순으로 내려간다(사진 고르기와 같은 순서).
 */
export function copyFor(keywordName: string, categorySlug: string | null): TopicCopy {
  const topic = topicOf(keywordName)
  const base = (topic && TABLE[topic]) || (categorySlug && TABLE[categorySlug]) || TABLE.general
  return {
    symptoms: base.symptoms.map((s) => fill(s, keywordName)),
    preventionTips: base.preventionTips.map((s) => fill(s, keywordName)),
    faqs: base.faqs.map((f) => ({ q: fill(f.q, keywordName), a: fill(f.a, keywordName) })),
    diyVsPro: fill(base.diyVsPro, keywordName),
    photoNote: fill(base.photoNote, keywordName),
  }
}
