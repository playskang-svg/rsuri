// 분야 슬러그로 떨어지는 경우를 위한 별칭 — lib/keyword-copy.ts와 같은 규칙.
for (const [alias, topic] of Object.entries(PARTS_INDEX.topicAliases)) {
  TABLE[alias] = TABLE[topic]
}

// ── 사이트맵과 어긋나지 않게 ──
// 사이트맵은 next build보다 먼저 도는 별도 node 프로세스라 이 파일(TS)을 못 읽는다.
// 그래서 주소 꼬리 목록은 lib/data/parts-index.json에도 있고, 둘이 어긋나면
// 사이트맵에 없는 페이지가 조용히 생긴다. 여기서 즉시 죽여 빌드에서 잡는다.
for (const [topic, expected] of Object.entries(PARTS_INDEX.suffixes)) {
  const actual = (TABLE[topic] ?? []).map((p) => p.suffix)
  if (actual.join(',') !== (expected as string[]).join(',')) {
    throw new Error(
      `keyword-parts: '${topic}' 항목이 data/parts-index.json과 다릅니다. ` +
        `JSON=[${(expected as string[]).join(',')}] TS=[${actual.join(',')}] — 양쪽을 같이 고치세요.`,
    )
  }
}

/** 이 키워드에 딸린 세부 항목. 이름에서 읽은 주제 → 분야 → general 순. */
export function partsFor(keywordName: string, categorySlug: string | null): SubItem[] {
  const topic = topicOf(keywordName)
  return (topic && TABLE[topic]) || (categorySlug && TABLE[categorySlug]) || TABLE.general
}

/** 세부 페이지 주소. 상위 슬러그 뒤에 꼬리를 붙인다. */
export const partSlug = (parentSlug: string, part: SubItem) => `${parentSlug}-${part.suffix}`

/**
 * 세부 페이지 이름 — 상위 키워드를 앞에 붙인다("방문복원 방문처짐").
 * short의 공백은 뗀다. 제목이 한 덩어리로 읽혀야 검색어와 모양이 같다.
 */
export const partName = (parentName: string, part: SubItem) =>
  `${parentName} ${part.short.replace(/\s+/g, '')}`
