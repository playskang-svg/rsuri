// 세부 시공 항목 — 키워드 한 개를 증상 단위로 쪼갠 하위 페이지.
//
// ── 왜 ──
// "문수리" 한 장으로는 찾아오는 검색어를 다 못 받는다. 사람들은 "문 처짐",
// "문 안 닫힘", "도어락 교체"처럼 증상으로 검색한다. 그래서 키워드 밑에 증상별
// 항목을 두고, 각각을 지역 페이지와 같은 구조의 독립 페이지로 만든다.
//
// ── 이름 규칙 ──
// 페이지 이름은 상위 키워드를 앞에 붙인다 — "방문복원 방문처짐".
// 카드에 보이는 제목(short)에는 가운뎃점(·)을 쓰지 않는다. 한 항목에 증상 하나다.
//
// ── 주소 ──
// `${상위슬러그}-${suffix}` 를 최상위 주소로 쓴다. 지역 경로(/{키워드}/{지역})와
// 겹치지 않고, 하위 지역 페이지가 생기면 그대로 /{세부슬러그}/{지역}로 확장된다.

